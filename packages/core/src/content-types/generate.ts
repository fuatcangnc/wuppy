import { type Collection, type FieldType } from "./index.ts";

const pascal = (s: string) => s.replace(/(^|-)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase());

function tsType(field: FieldType): string {
	const f = typeof field === "string" ? { type: field, multiple: false } : field;
	const many = (t: string) => ("multiple" in f && f.multiple ? `${t}[]` : t);
	switch (f.type) {
		case "boolean":
			return "boolean";
		case "number":
			return "number";
		case "list":
			return "string[]";
		case "json":
			return "unknown";
		case "byline":
			return "string | Array<string | { byline: string; role?: string }>";
		case "section":
			return "string[]";
		case "taxonomy":
		case "reference":
			return "multiple" in f && f.multiple ? "string[]" : "string | string[]";
		case "select":
			return many("options" in f && f.options?.length ? f.options.map((o) => JSON.stringify(o)).join(" | ") : "string");
		case "repeater":
			return `Array<${obj("fields" in f && f.fields ? f.fields : {})}>`;
		case "blocks": {
			const blocks = "blocks" in f && f.blocks ? Object.entries(f.blocks) : [];
			return blocks.length
				? `Array<${blocks.map(([name, fields]) => `{ type: ${JSON.stringify(name)} } & ${obj(fields)}`).join(" | ")}>`
				: "unknown[]";
		}
		default:
			return "string";
	}
}

function obj(fields: Record<string, FieldType>): string {
	const rows = Object.entries(fields).map(([name, f]) => {
		const required = typeof f !== "string" && f.required && !f.showIf;
		return `${JSON.stringify(name)}${required ? "" : "?"}: ${tsType(f)}`;
	});
	return `{ ${rows.join("; ")}${rows.length ? "; " : ""}[key: string]: unknown }`;
}

/** A `.d.ts` with one frontmatter interface per collection, regenerated whenever the schema changes. */
export function generateTypes(collections: readonly Collection[]): string {
	const out = ["// Generated by `wuppycms types`. Do not edit.", ""];
	for (const c of collections) out.push(`export type ${pascal(c.name)}Data = ${obj(c.fields)};`);
	out.push("", `export interface WuppyCollections {`);
	for (const c of collections) out.push(`\t${JSON.stringify(c.name)}: ${pascal(c.name)}Data;`);
	out.push("}", "");
	return out.join("\n");
}
